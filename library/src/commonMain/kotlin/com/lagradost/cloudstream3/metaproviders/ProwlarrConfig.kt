package com.lagradost.cloudstream3.metaproviders

/**
 * Where the user's Prowlarr instance lives, so the prowlarr plugin can query it.
 *
 * Prowlarr is self hosted, so the host and API key are per user. The app owns the
 * settings (Settings -> Player -> Prowlarr) and assigns these at startup, the same
 * way it hands [tmdbApiKeyOverride] to the metadata providers: a plugin runs in its
 * own classloader and cannot reach the app's preferences or storage itself, and
 * `Plugin.openSettings` is an app internal hook a .cs3 cannot reach.
 *
 * Both stay null until the app sets them, and a plugin must treat that as
 * "not configured" rather than guessing a host.
 */
var prowlarrHost: String? = null

/** Prowlarr's own API key, generated by Prowlarr and shown in its Settings -> General. */
var prowlarrApiKey: String? = null

/** The configured instance, or null when the host is missing or not an http(s) URL. */
fun prowlarrBaseUrl(): String? =
    prowlarrHost?.trim()?.trimEnd('/')?.takeIf { it.isNotEmpty() && it.startsWith("http") }